"""
Google Gemini Native REST Adapter using httpx.
"""

import time
import logging
from typing import List, Dict
import httpx

from .base import BaseAIAdapter, AIProviderError, AIAuthError, AIRateLimitError, AITimeoutError

logger = logging.getLogger("attendai.ai.gemini")


class GeminiAdapter(BaseAIAdapter):
    """Adapter for Google Gemini REST API with auto-retry and high-demand resilience."""

    DEFAULT_BASE_URL = "https://generativelanguage.googleapis.com/v1beta"

    def __init__(self, api_key: str, model: str = "gemini-3.6-flash", base_url: str = "", timeout_seconds: int = 30):
        super().__init__(api_key, model, base_url or self.DEFAULT_BASE_URL, timeout_seconds)
        if self.model in ("gemini-1.5-flash", "gemini-2.5-flash"):
            self.model = "gemini-3.6-flash"

    def generate_response(
        self,
        system_instruction: str,
        messages: List[Dict[str, str]],
        context_data: str = ""
    ) -> str:
        if not self.api_key:
            raise AIAuthError("Google Gemini API key is missing. Please set AI_API_KEY in .env.")

        # Ensure model doesn't have duplicate models/ prefix
        model_name = self.model.strip()
        if model_name.startswith("models/"):
            model_name = model_name[7:]

        # Combine context data into system instruction if present
        full_system_instruction = system_instruction
        if context_data:
            full_system_instruction += f"\n\n--- REAL-TIME ATTENDAI SYSTEM & DATABASE CONTEXT ---\n{context_data}"

        # Format conversation messages for Gemini (roles: 'user' and 'model')
        contents = []
        for msg in messages:
            role = "model" if msg.get("role") in ("assistant", "model") else "user"
            content = msg.get("content", "").strip()
            if content:
                contents.append({
                    "role": role,
                    "parts": [{"text": content}]
                })

        if not contents:
            contents.append({"role": "user", "parts": [{"text": "Hello"}]})

        payload = {
            "systemInstruction": {
                "parts": [{"text": full_system_instruction}]
            },
            "contents": contents,
            "generationConfig": {
                "temperature": 0.3,
                "maxOutputTokens": 2048,
            }
        }

        # Resilient model fallback candidates in case of 503 high-demand spikes
        models_to_try = [model_name]
        for alt in ("gemini-3.5-flash", "gemini-3.5-flash-lite"):
            if alt not in models_to_try:
                models_to_try.append(alt)

        last_error = None
        for current_model in models_to_try:
            endpoint = f"{self.base_url.rstrip('/')}/models/{current_model}:generateContent?key={self.api_key}"

            for attempt in range(2):
                try:
                    with httpx.Client(timeout=self.timeout_seconds) as client:
                        response = client.post(endpoint, json=payload, headers={"Content-Type": "application/json"})
                except httpx.TimeoutException as exc:
                    logger.error("Gemini API request timed out: %s", exc)
                    raise AITimeoutError("Gemini API request timed out. Please try again.") from exc
                except httpx.RequestError as exc:
                    logger.error("Gemini API connection error: %s", exc)
                    raise AIProviderError(f"Network error communicating with Gemini API: {exc}") from exc

                if response.status_code == 200:
                    try:
                        data = response.json()
                        candidates = data.get("candidates", [])
                        if not candidates:
                            prompt_feedback = data.get("promptFeedback", {})
                            block_reason = prompt_feedback.get("blockReason")
                            if block_reason:
                                return f"The request was filtered by safety policies ({block_reason})."
                            return "No response was generated by the model."

                        candidate = candidates[0]
                        content = candidate.get("content", {})
                        parts = content.get("parts", [])
                        if parts and "text" in parts[0]:
                            return parts[0]["text"].strip()
                        return "No response text was returned."
                    except Exception as e:
                        logger.error("Failed to parse Gemini response: %s", e)
                        raise AIProviderError(f"Failed to parse Gemini API response: {e}") from e

                # Handle HTTP error statuses
                status = response.status_code
                err_msg = ""
                try:
                    err_json = response.json()
                    err_obj = err_json.get("error", {})
                    err_msg = err_obj.get("message", response.text)
                except Exception:
                    err_msg = response.text

                logger.warning("Gemini API returned HTTP %s for %s (attempt %d): %s", status, current_model, attempt + 1, err_msg)

                if status in (401, 403) or "API_KEY_INVALID" in err_msg or "PERMISSION_DENIED" in err_msg:
                    raise AIAuthError(f"Gemini API authentication failed: {err_msg}", status_code=status, details=err_msg)

                if status == 503 or "high demand" in err_msg.lower():
                    time.sleep(1.0)
                    last_error = err_msg
                    continue
                elif status == 429 or "RESOURCE_EXHAUSTED" in err_msg:
                    time.sleep(1.5)
                    last_error = err_msg
                    continue
                else:
                    raise AIProviderError(f"Gemini API error (HTTP {status}): {err_msg}", status_code=status, details=err_msg)

        if last_error and ("RESOURCE_EXHAUSTED" in last_error or "429" in str(last_error)):
            raise AIRateLimitError(f"Gemini API rate limit or quota exceeded: {last_error}", status_code=429, details=last_error)

        raise AIProviderError(f"Gemini API temporarily unavailable: {last_error}", status_code=503, details=last_error)
